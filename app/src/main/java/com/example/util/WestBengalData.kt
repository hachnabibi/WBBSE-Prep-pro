    fun getSchoolsForBlock(blockName: String?, districtName: String?): List<String> {
        if (!blockName.isNullOrBlank()) {
            val key = blockSchoolsMap.keys.firstOrNull { blockName.contains(it, ignoreCase = true) || it.contains(blockName, ignoreCase = true) }
            if (key != null && blockSchoolsMap[key]?.isNotEmpty() == true) {
                return blockSchoolsMap[key]!!
            }
        }
        return getSchoolsForDistrict(districtName)
    }

